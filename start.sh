#!/usr/bin/env bash
#
# ONEPASS — one command, from nothing to a running app.
#
#   ./start.sh
#
# Then open http://localhost:3000.
#
# This replaces the six-step sequence in docker-compose.yml's header. That
# sequence is correct and each step is worth understanding, but a person who
# wants to *look at the thing* should not have to run six commands in order and
# hand-write a file of secrets before the first page loads.
#
# What it does, and what it will not do:
#
#  · Generates a .env on first run, with real random secrets — 32 bytes for the
#    encryption key, a distinct database password, a distinct audit pepper. They
#    are generated on your machine and never leave it. Run it again and it uses
#    the file that is already there rather than rotating your keys out from under
#    a database that was sealed with them.
#  · Brings up Postgres and Redis and waits for them to actually answer, not
#    merely to exist.
#  · Applies the schema, the row-level security policies, the seed, and the
#    sample-window refresh, in the order they depend on each other.
#  · Runs the development server, because the production image is judged by the
#    production guard in apps/web/src/lib/env.ts — it refuses an http:// URL, the
#    sandbox payment provider and console delivery. Those refusals are the
#    feature. A laptop cannot honestly satisfy them, so this does not pretend to.
#
# For a public deployment with a real URL, see docs/deployment.md and render.yaml.
set -euo pipefail

cd "$(dirname "$0")"

green() { printf '\033[32m%s\033[0m\n' "$1"; }
bold()  { printf '\033[1m%s\033[0m\n' "$1"; }
die()   { printf '\033[31m%s\033[0m\n' "$1" >&2; exit 1; }

# ── prerequisites ────────────────────────────────────────────
command -v docker >/dev/null 2>&1 || die "Docker is not installed. Get it from https://docs.docker.com/get-docker/"
docker compose version >/dev/null 2>&1 || die "This needs Docker Compose v2 (it ships with Docker Desktop)."
docker info >/dev/null 2>&1 || die "Docker is installed but not running. Start Docker Desktop and try again."

# ── secrets, once ────────────────────────────────────────────
if [ -f .env ]; then
  green "→ .env exists, leaving it alone"
else
  bold "→ generating .env"

  # openssl where it exists, otherwise Python. One of the two is on every machine
  # this is likely to run on, and neither is worth adding as a dependency.
  rand_b64() {
    if command -v openssl >/dev/null 2>&1; then openssl rand -base64 32
    else python3 -c 'import base64,os;print(base64.b64encode(os.urandom(32)).decode())'
    fi
  }
  rand_hex() {
    if command -v openssl >/dev/null 2>&1; then openssl rand -hex 24
    else python3 -c 'import os;print(os.urandom(24).hex())'
    fi
  }

  cat > .env <<EOF
# Generated by ./start.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ).
#
# These are real secrets. They were generated on this machine and have never
# left it. .gitignore excludes this file; keep it that way.
#
# ENCRYPTION_KEY seals pass secrets, webhook signing secrets and credential
# claims with AES-256-GCM. Lose it and that data cannot be decrypted; change it
# and everything already sealed stops opening. Back it up before you rotate it,
# and put the old one in ENCRYPTION_KEYS_PREVIOUS when you do.

POSTGRES_USER=onepass
POSTGRES_DB=onepass
POSTGRES_PASSWORD=$(rand_hex)
POSTGRES_PORT=5432
REDIS_PORT=6379
APP_PORT=3000

NODE_ENV=development
APP_URL=http://localhost:3000

DATABASE_URL=postgresql://onepass:PASSWORD_PLACEHOLDER@postgres:5432/onepass
DIRECT_DATABASE_URL=postgresql://onepass:PASSWORD_PLACEHOLDER@postgres:5432/onepass
REDIS_URL=redis://redis:6379

ENCRYPTION_KEY=$(rand_b64)
ENCRYPTION_KEY_ID=v1
HASH_PEPPER=$(rand_hex)

SESSION_COOKIE_NAME=onepass_session
RATE_LIMIT_DISABLED=false

# No provider credentials: on a laptop, codes go to the container log and no
# payment is taken. Production refuses to start this way — see docs/integrations.md.
PAYMENT_PROVIDER=SANDBOX
EMAIL_PROVIDER=CONSOLE
SMS_PROVIDER=CONSOLE
LOG_LEVEL=info
EOF

  # Substitute the password into the two URLs, so it is written once above and
  # cannot drift from what Postgres was actually started with.
  PW="$(grep '^POSTGRES_PASSWORD=' .env | cut -d= -f2-)"
  # A portable in-place sed: BSD sed (macOS) requires an argument to -i.
  sed "s|PASSWORD_PLACEHOLDER|${PW}|g" .env > .env.tmp && mv .env.tmp .env

  green "  wrote .env with freshly generated secrets"
fi

# ── dependencies ─────────────────────────────────────────────
bold "→ starting Postgres and Redis"
docker compose up -d postgres redis

# Asked of the services themselves rather than read out of `docker compose ps`.
# The `--format` template that prints health has changed shape between Compose
# releases, and a status string that stops matching turns into a script that
# waits the full two minutes and then runs the schema step against a database
# that is not up — which fails confusingly, a long way from the actual cause.
# `pg_isready` and `redis-cli ping` mean the same thing on every version.
printf '  waiting for them to answer'
ready=0
for _ in $(seq 60); do
  if docker compose exec -T postgres pg_isready -U onepass -d onepass >/dev/null 2>&1 \
     && docker compose exec -T redis redis-cli ping >/dev/null 2>&1; then
    ready=1
    printf '\n'; green "  both answering"; break
  fi
  printf '.'; sleep 2
done
[ "$ready" = "1" ] || die "
Postgres and Redis did not come up within two minutes.
  docker compose logs postgres redis    # what they said
  docker compose down -v                # start over from empty"

# ── schema, policies, data ───────────────────────────────────
# Every step below is idempotent, which is why this is safe to re-run: the push
# is a diff, the policy file drops and recreates, and the seed short-circuits on
# a database that already has venues.
bold "→ schema"
docker compose --profile tools run --rm -T tools npm run db:push -- --force >/dev/null
green "  applied"

bold "→ row-level security"
# `drizzle-kit push` drops policies it does not know about, so this runs after
# every push rather than once. See docs/operations.md.
#
# A failure here stops the script rather than printing a note and carrying on.
# What this file installs is the tenant isolation — the three database roles, the
# grants, and the policies that stop one organization reading another's rows. A
# stack that came up without them would look completely normal and be wrong in
# the one way nobody would notice by clicking around.
if docker compose exec -T postgres \
     psql -v ON_ERROR_STOP=1 -U onepass -d onepass -f - < apps/web/src/db/isolation.sql >/dev/null 2>&1; then
  green "  3 roles, grants and policies applied"
else
  die "
Could not apply apps/web/src/db/isolation.sql.

This installs tenant isolation, so the script stops rather than leaving you with
a stack that looks fine and does not enforce it. To see the error:

  docker compose exec -T postgres \\
    psql -U onepass -d onepass -f - < apps/web/src/db/isolation.sql"
fi

bold "→ sample data"
docker compose --profile tools run --rm -T tools npm run db:seed >/dev/null
docker compose --profile tools run --rm -T tools npx tsx src/db/seed-credential.ts >/dev/null 2>&1 || true
docker compose --profile tools run --rm -T tools npm run db:refresh >/dev/null
green "  seeded, and the sample window is anchored to today"

# ── the app ──────────────────────────────────────────────────
bold "→ starting the app"
docker compose up -d app

printf '  waiting for the first page'
PORT="$(grep '^APP_PORT=' .env | cut -d= -f2-)"
URL="http://localhost:${PORT:-3000}"
up=0
for _ in $(seq 90); do
  if curl -fsS "$URL/api/health" >/dev/null 2>&1; then
    up=1; printf '\n'; break
  fi
  printf '.'; sleep 2
done

# Never announce a URL that does not answer. The first dev-server compile can be
# slow on a cold cache, so this says which it is rather than guessing.
if [ "$up" != "1" ]; then
  printf '\n'
  die "
The app did not answer at $URL within three minutes.

  docker compose logs -f app

If the log ends at \"Ready in …\" it is still compiling the first page — give it
a moment and reload. Anything else is the actual error."
fi

echo
green "ONEPASS is running."
echo
bold "  $URL"
echo
echo "  Sign in with any of these — the password for all of them is onepass-sample-password:"
echo "    meera@example.in                  a consumer"
echo "    owner@phoenix-cinemas.example     a merchant (the door console, deals, analytics)"
echo "    admin@onepass.example             platform operations"
echo
echo "  Logs:  docker compose logs -f app"
echo "  Stop:  docker compose down"
echo "  Reset: docker compose down -v   (this deletes the database)"
echo
echo "  Email and SMS codes are printed to the app log rather than sent, and no"
echo "  payment is taken — there are no provider credentials on a local run."
